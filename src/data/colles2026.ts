const collesById = new Map(colles2026.map((c) => [c.id, c]))

export function getCollaById(id: string): Colla | undefined {
  return collesById.get(id)
}

export function getCollesBySession(session: ConcursSession): Colla[] {
  return colles2026.filter((c) => c.concurs2026.session === session)
}

function normalizeText(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
}

export function searchColles(query: string): Colla[] {
  const q = normalizeText(query)
  if (!q) return colles2026
  return colles2026.filter((c) => {
    const haystack = normalizeText(`${c.name} ${c.shortName} ${c.municipality}`)
    return haystack.includes(q)
  })
}

